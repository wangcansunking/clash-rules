#!/usr/bin/env python3
"""Generate combined Clash rules and classical providers; --check detects drift."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def outputs():
    groups = json.loads((ROOT / 'domains.json').read_text())
    seen = set()
    rules = ['# Generated by scripts/generate.py from domains.json.', '# PROXY must match an existing client policy/group.', 'rules:']
    provider = ['# Generated by scripts/generate.py from domains.json.', '# Clash / Mihomo classical provider; policy belongs in RULE-SET.', 'payload:']
    for group, domains in groups.items():
        rules.append('  # ' + group)
        provider.append('  # ' + group)
        for domain in domains:
            assert re.fullmatch(r'(?:[a-z0-9](?:[a-z0-9-]*[a-z0-9])?\.)+[a-z]{2,}', domain), domain
            assert domain not in seen, 'duplicate: ' + domain
            seen.add(domain)
            rule = 'DOMAIN-SUFFIX,' + domain
            rules.append('  - ' + rule + ',PROXY')
            provider.append('  - ' + rule)
    return {
        name: '\n'.join(lines) + '\n'
        for names, lines in [
            (['proxy-rules.yaml', 'ai-rules.yaml'], rules),
            (['proxy-provider.yaml', 'ai-provider.yaml'], provider),
        ]
        for name in names
    }, len(seen)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    files, count = outputs()
    for name, content in files.items():
        target = ROOT / name
        if args.check:
            assert target.read_text() == content, 'out of date: ' + name
        else:
            target.write_text(content)
    print(f'{"Checked" if args.check else "Generated"} {len(files)} files, {count} rules each')
